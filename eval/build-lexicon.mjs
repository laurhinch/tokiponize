// Write src/lexicon.ts: the English words our spelling rules misread, from
// CMUdict. Only the disagreements; a miss falls through to the rules.
//
//   pip install cmudict && node eval/build-lexicon.mjs

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { toPhonemes } from "../dist/index.js";

const here = dirname(fileURLToPath(import.meta.url));

const raw = execFileSync("python", [join(here, "cmudict-fold.py")], {
  encoding: "utf8",
  maxBuffer: 64 * 1024 * 1024,
  // cmudict's data files are utf-8, a Windows codepage can't read them
  env: { ...process.env, PYTHONUTF8: "1", PYTHONIOENCODING: "utf-8" },
});

const lines = raw.split("\n").filter(Boolean);
const kept = [];
let agreed = 0;
for (const line of lines) {
  const sp = line.indexOf(" ");
  const word = line.slice(0, sp);
  const ph = line.slice(sp + 1).trim();
  if (!ph) continue;
  if (toPhonemes(word) === ph) {
    agreed++;
    continue;
  }
  kept.push(`${word} ${ph}`);
}

const out = `// generated by eval/build-lexicon.mjs, do not edit
//
// English words scripts.ts misreads, from CMUdict, folded into the toki
// pona inventory. One "word phonemes" pair per line.
export const LEXICON = ${JSON.stringify(kept.join("\n"))};
`;

writeFileSync(join(here, "..", "src", "lexicon.ts"), out);
console.log(
  `${lines.length} cmudict entries, rules agree on ${agreed}, ` +
    `wrote ${kept.length} to src/lexicon.ts ` +
    `(${(out.length / 1024 / 1024).toFixed(2)} MB)`,
);
