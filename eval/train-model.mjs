// Learn rewrite costs from the Wikidata pairs and emit src/model.ts.
// Uses the same train/holdout split as tune.mjs.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { toPhonemes } from "../dist/index.js";
import { capWords, levenshtein, splitWords, usableLabel } from "./lib.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const rows = readFileSync(join(here, "data", "wikidata-tok.jsonl"), "utf8")
  .split("\n")
  .filter(Boolean)
  .map((l) => JSON.parse(l));

// pair each toki pona word with the closest source word; far pairs are
// endonym mismatches and would poison the counts
const pairs = new Map();
for (const row of rows) {
  if (Number(row.id.slice(1)) % 10 >= 6) continue;
  for (const att of capWords(row.tok)) {
    const target = att.toLowerCase();
    let best = null;
    for (const label of Object.values(row.labels)) {
      if (!usableLabel(label)) continue;
      for (const word of splitWords(label)) {
        const ph = toPhonemes(word);
        if (!ph || ph.length > 24) continue;
        const d = levenshtein(ph, target) / Math.max(ph.length, target.length);
        if (!best || d < best.d) best = { ph, d };
      }
    }
    if (best && best.d <= 0.6) pairs.set(`${best.ph} ${target}`, [best.ph, target]);
  }
}
const data = [...pairs.values()];
console.log(`${data.length} training pairs`);

// ops rewrite up to 2 source chars into up to 2 target chars
const MAXS = 2;
const MAXT = 2;

function heuristicCost(s, t) {
  if (s === t) return 0.1;
  const vow = (c) => "aeiou".includes(c);
  if (s.length === 1 && t.length === 1) return vow(s) === vow(t) ? 1.2 : 2;
  if (!s || !t) return 2.2;
  return 2.5;
}

let costs = null;
const cost = (s, t) => {
  if (costs) return costs.get(`${s}\t${t}`) ?? 8;
  return heuristicCost(s, t);
};

// best alignment path for one pair, returns the ops used
function align(src, tgt) {
  const m = src.length;
  const n = tgt.length;
  const dp = Array.from({ length: m + 1 }, () => new Array(n + 1).fill(Infinity));
  const back = Array.from({ length: m + 1 }, () => new Array(n + 1));
  dp[0][0] = 0;
  for (let i = 0; i <= m; i++) {
    for (let j = 0; j <= n; j++) {
      if (dp[i][j] === Infinity) continue;
      for (let ls = 0; ls <= MAXS && i + ls <= m; ls++) {
        for (let lt = 0; lt <= MAXT && j + lt <= n; lt++) {
          if (!ls && !lt) continue;
          const s = src.slice(i, i + ls);
          const t = tgt.slice(j, j + lt);
          const c = dp[i][j] + cost(s, t);
          if (c < dp[i + ls][j + lt]) {
            dp[i + ls][j + lt] = c;
            back[i + ls][j + lt] = [i, j, s, t];
          }
        }
      }
    }
  }
  if (dp[m][n] === Infinity) return [];
  const ops = [];
  let i = m;
  let j = n;
  while (i || j) {
    const [pi, pj, s, t] = back[i][j];
    ops.push([s, t]);
    i = pi;
    j = pj;
  }
  return ops;
}

for (let iter = 0; iter < 3; iter++) {
  const counts = new Map();
  const bySource = new Map();
  for (const [src, tgt] of data) {
    for (const [s, t] of align(src, tgt)) {
      const key = `${s}\t${t}`;
      counts.set(key, (counts.get(key) ?? 0) + 1);
      bySource.set(s, (bySource.get(s) ?? 0) + 1);
    }
  }
  costs = new Map();
  for (const [key, c] of counts) {
    const s = key.split("\t")[0];
    costs.set(key, -Math.log((c + 0.1) / (bySource.get(s) + 5)));
  }
  console.log(`iter ${iter + 1}: ${counts.size} ops`);
  // prune rare ops after the last iteration
  if (iter === 2) {
    for (const [key, c] of counts) if (c < 3) costs.delete(key);
  }
}

const model = {};
for (const [key, c] of costs) {
  const [s, t] = key.split("\t");
  (model[s] ??= {})[t] = Math.round(c * 1000) / 1000;
}

const out = `// generated by eval/train-model.mjs, do not edit
export const MODEL: Record<string, Record<string, number>> = ${
  JSON.stringify(model)
};
`;
writeFileSync(join(here, "..", "src", "model.ts"), out);
console.log(`wrote src/model.ts (${Object.keys(model).length} sources)`);
