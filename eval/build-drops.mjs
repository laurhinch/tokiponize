// Write src/drops.ts: how often each consonant is deleted, by where it sits.
// A final k goes 79% of the time and a final n 1%, since toki pona has an n
// coda to put it in. Training split only.
//
//   node eval/build-drops.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { toPhonemes } from "../dist/index.js";
import { levenshtein, nameWords, splitWords, usableLabel } from "./lib.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const rows = readFileSync(join(here, "data", "wikidata-tok.jsonl"), "utf8")
  .split("\n")
  .filter(Boolean)
  .map((l) => JSON.parse(l))
  .filter((r) => Number(r.id.slice(1)) % 10 < 6);

// same pairing train-model.mjs uses: the source word that best explains the
// attested form, and only when it explains it well enough
const pairs = [];
for (const row of rows) {
  for (const att of nameWords(row.tok)) {
    let best = null;
    for (const label of Object.values(row.labels)) {
      if (!usableLabel(label)) continue;
      for (const w of splitWords(label)) {
        const ph = toPhonemes(w);
        if (!ph || ph.length > 24) continue;
        const d = levenshtein(ph, att) / Math.max(ph.length, att.length);
        if (!best || d < best.d) best = { ph, d };
      }
    }
    if (best && best.d <= 0.6) pairs.push([best.ph, att]);
  }
}

const VOWELS = new Set([..."aeiou"]);
const POS = ["i", "m", "f"];
const stat = new Map(); // phoneme -> [[kept, dropped] per position]

for (const [src, tgt] of pairs) {
  const m = src.length;
  const n = tgt.length;
  const d = Array.from({ length: m + 1 }, (_, i) =>
    Array.from({ length: n + 1 }, (_, j) => (i === 0 ? j : j === 0 ? i : 0)));
  for (let i = 1; i <= m; i++) {
    for (let j = 1; j <= n; j++) {
      d[i][j] = Math.min(
        d[i - 1][j] + 1,
        d[i][j - 1] + 1,
        d[i - 1][j - 1] + (src[i - 1] === tgt[j - 1] ? 0 : 1),
      );
    }
  }
  let i = m;
  let j = n;
  while (i > 0) {
    let dropped = false;
    if (j > 0 && d[i][j] === d[i - 1][j - 1] + (src[i - 1] === tgt[j - 1] ? 0 : 1)) {
      i--;
      j--;
    } else if (d[i][j] === d[i - 1][j] + 1) {
      dropped = true;
      i--;
    } else {
      j--;
      continue;
    }
    const ch = src[i];
    if (VOWELS.has(ch)) continue;
    const pos = i === 0 ? 0 : i === m - 1 ? 2 : 1;
    const e = stat.get(ch) ?? [[0, 0], [0, 0], [0, 0]];
    e[pos][dropped ? 1 : 0]++;
    stat.set(ch, e);
  }
}

// too few counts to say anything, so leave it out and let the search fall
// back to its flat penalty
const MIN = 25;
const out = {};
for (const [ch, e] of [...stat].sort()) {
  const row = e.map(([kept, dropped]) => {
    const total = kept + dropped;
    if (total < MIN) return null;
    return Math.round((dropped / total) * 1000) / 1000;
  });
  if (row.some((r) => r !== null)) out[ch] = row;
}

const body = Object.entries(out)
  .map(([ch, row]) => `  ${ch}: [${row.map((r) => (r === null ? "null" : r)).join(", ")}],`)
  .join("\n");

writeFileSync(
  join(here, "..", "src", "drops.ts"),
  `// generated by eval/build-drops.mjs, do not edit
//
// How often each consonant is deleted, as [word-initial, medial, final].
// null where there was too little to count.
export const DROP: Record<string, Array<number | null>> = {
${body}
};
`,
);

console.log(`${pairs.length} pairs`);
console.log("ph   initial  medial   final");
for (const [ch, row] of Object.entries(out)) {
  const f = (r) => (r === null ? "    .  " : `${(100 * r).toFixed(0).padStart(5)}% `);
  console.log(` ${ch}  ${row.map(f).join(" ")}`);
}
